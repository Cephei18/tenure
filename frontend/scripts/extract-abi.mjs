// Copies ONLY the ABI fragments the frontend reads from the forge build artifacts in ../out/ to src/abi/.
// Run after `forge build` (repo root): npm run abi. The output is committed, so CI needs no Foundry.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const want = {
  TenureHook: ["tierOf", "budgetOf", "recordCount", "settlePointer", "lastRebalanceBlock"],
  CuratedVault: ["relayFrozen", "totalSupply", "balanceOf", "freezeReceiver", "DEAD_SHARES"],
  DemoDirector: ["ticks", "rounds", "frozenAt", "poisonAt", "note"],
};
const artifact = { TenureHook: "TenureHook.sol", CuratedVault: "CuratedVault.sol", DemoDirector: "DemoActors.sol" };

for (const [name, fns] of Object.entries(want)) {
  const abi = JSON.parse(readFileSync(join(root, "out", artifact[name], `${name}.json`), "utf8")).abi;
  const picked = fns.map((fn) => {
    const f = abi.find((x) => x.type === "function" && x.name === fn);
    if (!f) throw new Error(`${name}.${fn} not in out/${artifact[name]}`);
    return f;
  });
  const file = join(root, "frontend", "src", "abi", `${name}.ts`);
  writeFileSync(file, `// Generated by scripts/extract-abi.mjs from out/${artifact[name]}/${name}.json. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(picked, null, 2)} as const;\n`);
  console.log(`${name}: ${picked.length} fragments -> src/abi/${name}.ts`);
}
